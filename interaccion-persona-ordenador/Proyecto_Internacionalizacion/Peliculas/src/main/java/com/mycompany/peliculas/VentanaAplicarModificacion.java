    private void aplicarCambios(String archivo) {
    File archivoFile = new File(archivo);
    StringBuilder contenidoActualizado = new StringBuilder();

    try (BufferedReader reader = new BufferedReader(new FileReader(archivoFile))) {
        String linea;

        while ((linea = reader.readLine()) != null) {
            String[] datos = linea.split("\t");

            if (datos[0].trim().equals(pelicula[0].trim())) {
                contenidoActualizado.append(nuevoTituloField.getText().trim()).append("\t")
                        .append(nuevoEstrenoField.getText().trim()).append("\t")
                        .append(nuevoDirectorField.getText().trim()).append("\n");
            } else {
                contenidoActualizado.append(linea).append("\n");
            }
        }
    } catch (IOException e) {
        System.err.println("Error leyendo el archivo: " + e.getMessage());
        return;
    }

    try (BufferedWriter writer = new BufferedWriter(new FileWriter(archivoFile))) {
        writer.write(contenidoActualizado.toString());
    } catch (IOException e) {
        System.err.println("Error escribiendo el archivo: " + e.getMessage());
    }
}


    
    public void obtenerPelicula(String[] peliculaModificar){
        pelicula = peliculaModificar;
        if (pelicula != null && pelicula.length >= 3) {
            nuevoTituloField.setText(pelicula[0]);
            nuevoEstrenoField.setText(pelicula[1]);
            nuevoDirectorField.setText(pelicula[2]);
        } else {
            System.err.println("Los datos de la película son inválidos.");
        }
    }
    
