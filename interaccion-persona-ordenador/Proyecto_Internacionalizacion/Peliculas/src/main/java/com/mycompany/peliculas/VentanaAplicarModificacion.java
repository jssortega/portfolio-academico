    private void aplicarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_aplicarButtonActionPerformed
        emptyPanel.addPropertyChangeListener(e -> {
            String prop = e.getPropertyName();
            if (emptyDialog.isVisible() && e.getSource() == emptyPanel && prop.equals(JOptionPane.VALUE_PROPERTY)) {
                emptyDialog.setVisible(false);
                emptyDialog.dispose();
                emptyPanel.setValue(null);
            }
        });
        
        if(nuevoTituloField.getText().isEmpty() || nuevoEstrenoField.getText().isEmpty() || nuevoDirectorField.getText().isEmpty()){
            emptyDialog.setLocationRelativeTo(this);
            emptyDialog.setVisible(true);
        } else{
            aplicarCambios("datos.tsv");
            dispose();
        }
    }//GEN-LAST:event_aplicarButtonActionPerformed

